4. Create Product Catalog View

CREATE VIEW vw_product_catalog AS
SELECT Product_ID, Product_Name, Category, Unit_Price
FROM Product;

5. Display Product Catalog

SELECT * FROM vw_product_catalog
ORDER BY Product_ID;

6. Create Low-Stock View

CREATE VIEW vw_low_stock AS
SELECT Product_ID, Product_Name, Stock_Qty
FROM Product
WHERE Stock_Qty < 10;

7. Display Low-Stock Products

SELECT * FROM vw_low_stock
ORDER BY Product_ID;

8. Replace Low-Stock View

CREATE OR REPLACE VIEW vw_low_stock AS
SELECT Product_ID, Product_Name, Category, Stock_Qty
FROM Product
WHERE Stock_Qty <= 12;

9. Insert Product and Generate Automatic ID

INSERT INTO Product (Product_Name, Category, Unit_Price, Stock_Qty, Warehouse)
VALUES ('Webcam', 'Electronics', 2200, 18, 'Chennai');

SELECT LAST_INSERT_ID() AS New_Product_ID;

10. Create Index on Category

CREATE INDEX idx_product_category
ON Product(Category);

11. Display Indexes

SHOW INDEX FROM Product;

12. Display Query Execution Plan

EXPLAIN SELECT * FROM Product
WHERE Category = 'Electronics';

13. Create Transaction and Savepoint

START TRANSACTION;

UPDATE Product
SET Stock_Qty = Stock_Qty - 5
WHERE Product_ID = 1001;

SAVEPOINT sp_after_keyboard;

UPDATE Product
SET Stock_Qty = Stock_Qty - 3
WHERE Product_ID = 1002;

SELECT Product_ID, Stock_Qty
FROM Product
WHERE Product_ID IN (1001, 1002)
ORDER BY Product_ID;

14. Roll Back to Savepoint

ROLLBACK TO SAVEPOINT sp_after_keyboard;

SELECT Product_ID, Stock_Qty
FROM Product
WHERE Product_ID IN (1001, 1002)
ORDER BY Product_ID;

15. Commit Transaction

COMMIT;

SELECT Product_ID, Stock_Qty
FROM Product
WHERE Product_ID IN (1001, 1002)
ORDER BY Product_ID;

16. Demonstrate Full Rollback

START TRANSACTION;

UPDATE Product
SET Stock_Qty = 0
WHERE Product_ID = 1003;

ROLLBACK;

SELECT Product_ID, Stock_Qty
FROM Product
WHERE Product_ID = 1003;

17. Drop Secondary Index

DROP INDEX idx_product_category ON Product;

SHOW INDEX FROM Product;

18. Verify Product Records

SELECT COUNT(*) AS Total_Products
FROM Product;

SELECT Product_ID, Stock_Qty
FROM Product
WHERE Product_ID IN (1001, 1002, 1003);

SHOW FULL TABLES IN WarehouseDB;




